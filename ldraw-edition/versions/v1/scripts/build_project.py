def antenna(kind,base,rf,lift=0,tag=''):
    w=17.5 if kind=='wifi' else 7
    fy=18.7 if kind=='wifi' else 3
    feed=translated(base,(w/2,fy,.5))
    plug=translated(rf,(0,0,lift))
    tail=translated(plug,(0,2.65,.32))
    side=1 if kind=='wifi' else -1
    mesh=Mesh()
    mesh.tube(bezier(tail,(tail[0],tail[1]+18,tail[2]+1),(feed[0]-12*side,feed[1]+9,feed[2]+2),feed))
    nm=f'{tag}-{kind}-cable.dat'
    mesh.save(nm,f'{kind} cable layout, authored separately from manufacturer CAD')
    return [ref(f'{kind}-fpc.dat',base),ref('rf-plug.dat',plug),ref(nm)]

