def text_line(s,x,y,size=20,bold=False):
    font=f'Arial,{size},-1,5,{75 if bold else 50},0,0,0,0,0'
    return [f'0 !LPUB INSERT TEXT "{s}" "{font}" "#191919"',f'0 !LPUB INSERT TEXT PLACEMENT LOCAL TOP_LEFT PAGE INSIDE OFFSET {x} {y}']

