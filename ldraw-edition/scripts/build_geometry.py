def p(v):
    x,y,z=v
    return f'{x*2.5:.4f} {-z*2.5:.4f} {y*2.5:.4f}'

def part_header(name,desc):
    return [f'0 {desc}',f'0 Name: {name}','0 Author: Programmatic assembly guide',
            '0 !LDRAW_ORG Unofficial_Part','0 BFC NOCERTIFY']

class Mesh:
    def __init__(self): self.lines=[]
    def face(self,pts,c=15):
        self.lines.append(f'{len(pts)} {c} '+' '.join(p(v) for v in pts))
    def edge(self,a,b,c=0): self.lines.append(f'2 {c} {p(a)} {p(b)}')
    def prism(self,xy,z,h,c=15,edges=True):
        lo=[(x,y,z) for x,y in xy]
        hi=[(x,y,z+h) for x,y in xy]
        # Triangle fan handles convex outlines without introducing drawn seams.
        for i in range(1,len(xy)-1):
            self.face([hi[0],hi[i],hi[i+1]],c)
            self.face([lo[0],lo[i+1],lo[i]],c)
        for i in range(len(xy)):
            j=(i+1)%len(xy)
            self.face([lo[i],lo[j],hi[j],hi[i]],c)
            if edges:
                self.edge(hi[i],hi[j])
                self.edge(lo[i],lo[j])
                self.edge(lo[i],hi[i])
    def box(self,x,y,z,w,l,h,c=15):
        self.prism([(x,y),(x+w,y),(x+w,y+l),(x,y+l)],z,h,c)
    def tube(self,points,r=.565,c=0):
        rings=[]
        n=10
        for i,pt in enumerate(points):
            a=points[max(0,i-1)]
            b=points[min(len(points)-1,i+1)]
            d=[b[j]-a[j] for j in range(3)]
            dnorm=math.sqrt(sum(t*t for t in d))
            d=[t/dnorm for t in d]
            # Stable frame for nearly horizontal cable runs.
            u=[-d[1],d[0],0]
            norm=math.sqrt(sum(t*t for t in u))
            if norm<1e-5: u=[1,0,0]
            else: u=[t/norm for t in u]
            v=[d[1]*u[2]-d[2]*u[1],d[2]*u[0]-d[0]*u[2],d[0]*u[1]-d[1]*u[0]]
            rings.append([tuple(pt[j]+r*(u[j]*math.cos(k*2*math.pi/n)+v[j]*math.sin(k*2*math.pi/n)) for j in range(3)) for k in range(n)])
        for i in range(len(rings)-1):
            for k in range(n):
                j=(k+1)%n
                self.face([rings[i][k],rings[i][j],rings[i+1][j],rings[i+1][k]],c)
    def save(self,name,desc):
        (PARTS/name).write_text('\n'.join(part_header(name,desc)+self.lines)+'\n')

def bezier(a,b,c,d,n=28):
    return [tuple((1-t)**3*a[j]+3*(1-t)**2*t*b[j]+3*(1-t)*t*t*c[j]+t**3*d[j] for j in range(3)) for t in [i/n for i in range(n+1)]]

def ref(name,xyz=(0,0,0),scale=1,color=16):
    return f'1 {color} {p(xyz)} {scale} 0 0 0 {scale} 0 0 0 {scale} {name}'

def board(name,xyz=(0,0,0),scale=1):
    return [ref(f'{name}-{kind}.dat',xyz,scale)
            for kind in ('official', 'kit-details', 'markings')]

def translated(base,delta): return tuple(a+b for a,b in zip(base,delta))

