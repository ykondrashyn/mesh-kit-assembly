def embed(lines):
    lines += ['0 NOFILE']
    for path in sorted(PARTS.glob('*.dat')):
        lines += [f'0 FILE {path.name}',path.read_text().rstrip(),'0 NOFILE']
    return '\n'.join(lines)+'\n'

