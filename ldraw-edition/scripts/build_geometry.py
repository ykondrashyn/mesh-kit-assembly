def antenna(kind,base,rf,lift=0,tag=''):
    w=17.5 if kind=='wifi' else 7
    fy=18.7 if kind=='wifi' else 3
    feed=translated(base,(w/2,fy,.5))
    plug=translated(rf,(0,0,lift))
    tail=translated(plug,(0,2.65,.32))
