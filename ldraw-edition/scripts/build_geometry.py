def marking(name, label, cx, cy, z, height):
    mesh = Mesh()
    stroke = height*.095
    left = cx-((len(label)-1)*.85+.62)*height/2
    bottom = cy-height/2
    for index, char in enumerate(label):
        for path in GLYPHS[char]:
            points = [(left+(index*.85+x)*height, bottom+y*height) for x,y in path]
            for (ax,ay),(bx,by) in zip(points,points[1:]):
                length = math.hypot(bx-ax,by-ay)
                dx,dy = -(by-ay)*stroke/length/2, (bx-ax)*stroke/length/2
                mesh.face([(ax+dx,ay+dy,z),(bx+dx,by+dy,z),
                           (bx-dx,by-dy,z),(ax-dx,ay-dy,z)],72)
            # Rounded joins prevent gaps between strokes at small render sizes.
            for x,y in points:
                ring=[(x+stroke/2*math.cos(i*math.pi/4),
                       y+stroke/2*math.sin(i*math.pi/4),z) for i in range(8)]
                for i in range(1,7):
                    mesh.face([ring[0],ring[i],ring[i+1]],72)
    mesh.save(f'{name}-markings.dat',f'{label}: simplified printed device identifier')

